function renderGoogleProfile(profile, { persist = false } = {}) {
  const account = document.querySelector("#google-account");
  const signInButton = document.querySelector("#google-signin-button");
  account.replaceChildren();

  if (profile.picture) {
    try {
      const picture = new URL(profile.picture);
      if (picture.protocol === "https:") {
        const avatar = document.createElement("img");
        avatar.src = picture.href;
        avatar.alt = "";
        avatar.addEventListener("error", () => avatar.remove(), { once: true });
        account.append(avatar);
      }
    } catch {
      // Ignore malformed profile photo URLs and retain the user's account name.
    }
  }

  const accountName = document.createElement("span");
  accountName.className = "google-account-name";
  accountName.textContent = profile.given_name || profile.name || profile.email;
  account.append(accountName);

  const signOutButton = document.createElement("button");
  signOutButton.className = "google-signout";
  signOutButton.type = "button";
  signOutButton.textContent = currentLanguage === "ar" ? "خروج" : "Sign out";
  signOutButton.setAttribute("aria-label", currentLanguage === "ar" ? "تسجيل الخروج من Google" : "Sign out of Google");
  signOutButton.addEventListener("click", () => {
    window.google?.accounts?.id.disableAutoSelect();
    localStorage.removeItem(googleProfileStorageKey);
    account.hidden = true;
    signInButton.hidden = false;
    showToast(translate("signedOut"));
  });
  account.append(signOutButton);
  account.hidden = false;
  signInButton.hidden = true;

  if (persist) {
    try {
      localStorage.setItem(googleProfileStorageKey, JSON.stringify({
        name: profile.name || "",
        given_name: profile.given_name || "",
        email: profile.email || "",
        picture: profile.picture || "",
      }));
    } catch (error) {
      console.error("Could not save the Google profile for this browser.", error);
    }
  }
}

function handleGoogleCredentialResponse(response) {
  try {
    // Decoded claims only populate the UI; a backend must verify the token signature before trusting them.
    const payloadPart = response.credential.split(".")[1];
    if (!payloadPart) throw new Error("Google returned an invalid credential.");
    const normalizedPayload = payloadPart.replace(/-/g, "+").replace(/_/g, "/");
    const paddedPayload = normalizedPayload.padEnd(Math.ceil(normalizedPayload.length / 4) * 4, "=");
    const payloadBytes = Uint8Array.from(atob(paddedPayload), (character) => character.charCodeAt(0));
    const profile = JSON.parse(new TextDecoder().decode(payloadBytes));
    const validIssuer = profile.iss === "https://accounts.google.com" || profile.iss === "accounts.google.com";
    const validCredential = profile.aud === googleClientId
      && validIssuer
      && Number(profile.exp) * 1000 > Date.now()
      && profile.email_verified === true;

    if (!validCredential) {
      showToast(translate("credentialInvalid"));
      return;
    }

    renderGoogleProfile(profile, { persist: true });
    showToast(translate("welcome", { name: profile.given_name || profile.name || "" }));
  } catch (error) {
    console.error("Google sign-in credential could not be read.", error);
    showToast(translate("googleSignInFailed"));
  }
}

function initializeGoogleSignIn() {
  if (!window.google?.accounts?.id) {
    showToast(translate("googleUnavailable"));
    return;
  }

  if (!googleSignInInitialized) {
    window.google.accounts.id.initialize({
      client_id: googleClientId,
      callback: handleGoogleCredentialResponse,
      context: "signin",
      ux_mode: "popup",
      auto_select: false,
    });
    googleSignInInitialized = true;
  }
  renderGoogleButton();
}

