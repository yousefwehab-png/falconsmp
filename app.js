function addPerspectiveTilt(container, selector, maxTilt = 5) {
  const resetTilt = (element) => {
    element.style.setProperty("--tilt-x", "0deg");
    element.style.setProperty("--tilt-y", "0deg");
  };

  container.addEventListener("pointermove", (event) => {
    if (event.pointerType === "touch" || window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;
    const card = event.target.closest(selector);
    if (!card || !container.contains(card)) return;

    const bounds = card.getBoundingClientRect();
    const horizontalPosition = (event.clientX - bounds.left) / bounds.width - 0.5;
    const verticalPosition = (event.clientY - bounds.top) / bounds.height - 0.5;
    card.style.setProperty("--tilt-x", `${verticalPosition * -maxTilt}deg`);
    card.style.setProperty("--tilt-y", `${horizontalPosition * maxTilt}deg`);
  });

  container.addEventListener("pointerleave", () => {
    container.querySelectorAll(selector).forEach(resetTilt);
  });
}

